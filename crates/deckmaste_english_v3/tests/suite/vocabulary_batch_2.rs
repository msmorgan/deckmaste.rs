#[test]
fn vocabulary_only_witnesses_preserve_counts_and_roles() {
    let mut failures = Vec::new();
    for &(word, card, text, category, count, role, span) in WITNESSES {
        let result = std::panic::catch_unwind(|| {
            assert_eq!(
                common::readings_on_card(card, text, category).len(),
                count,
                "{word}: {card}: {text}"
            );
            common::assert_constituents_on_card(card, text, category, &[(role, span)]);
        });
        if result.is_err() {
            failures.push(format!("{word}: {card}: {text}"));
        }
    }
    assert_eq!(failures, Vec::<String>::new());
}
